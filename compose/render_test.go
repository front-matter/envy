package compose

import (
	"errors"
	"strings"
	"testing"
)

func TestRender(t *testing.T) {
	tests := []struct {
		name  string
		input string
		want  string
	}{
		{
			name: "list merge in order, earlier sets win",
			input: `x-set-base: &base
  A: base-a
  B: base-b
x-set-web: &web
  B: web-b
  C: web-c
services:
  web:
    image: example
    environment:
      <<: [*base, *web]
`,
			want: `services:
  web:
    image: example
    environment:
      A: base-a
      B: base-b
      C: web-c
`,
		},
		{
			name: "single merge and explicit keys win, order kept",
			input: `x-set-app: &app
  A: from-set
  B: from-set
services:
  worker:
    environment:
      B: explicit
      <<: *app
      Z: last
`,
			want: `services:
  worker:
    environment:
      B: explicit
      A: from-set
      Z: last
`,
		},
		{
			name: "variables are not interpolated and quoting is kept",
			input: `x-set-app: &app
  INVENIO_SECRET_KEY: '${INVENIO_SECRET_KEY}'
  INVENIO_DEBUG: "${INVENIO_DEBUG:-false}"
services:
  web:
    environment:
      <<: [*app]
`,
			want: `services:
  web:
    environment:
      INVENIO_SECRET_KEY: '${INVENIO_SECRET_KEY}'
      INVENIO_DEBUG: "${INVENIO_DEBUG:-false}"
`,
		},
		{
			name: "x-envy and comments are removed, plain aliases expanded",
			input: `x-envy:
  HUGO_TITLE: Example
# command shared by web and worker
x-command: &cmd
  - celery
  - worker
services:
  # web describes the frontend
  web:
    command: *cmd # inline comment
volumes:
  data: null
`,
			want: `services:
  web:
    command:
      - celery
      - worker
volumes:
  data: null
`,
		},
		{
			name: "quoted << is an ordinary key",
			input: `services:
  web:
    labels:
      "<<": literal
`,
			want: `services:
  web:
    labels:
      "<<": literal
`,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := Render([]byte(tt.input), "")
			if err != nil {
				t.Fatalf("Render() error = %v", err)
			}
			if string(got) != tt.want {
				t.Fatalf("Render() mismatch\n--- got ---\n%s\n--- want ---\n%s", got, tt.want)
			}
		})
	}
}

func TestRenderHeader(t *testing.T) {
	got, err := Render([]byte("services: {}\n"), "Generated by envy render.\nDo not edit.")
	if err != nil {
		t.Fatalf("Render() error = %v", err)
	}
	if !strings.HasPrefix(string(got), "# Generated by envy render.\n# Do not edit.\nservices:") {
		t.Fatalf("unexpected header:\n%s", got)
	}
}

func TestRenderErrors(t *testing.T) {
	tests := []struct {
		name  string
		input string
	}{
		{name: "not a mapping", input: "- a\n- b\n"},
		{name: "invalid yaml", input: "services: [\n"},
		{name: "merge of a scalar", input: "x-a: &a scalar\nservices:\n  web:\n    environment:\n      <<: *a\n"},
		{name: "merge list with a scalar", input: "x-a: &a scalar\nservices:\n  web:\n    environment:\n      <<: [*a]\n"},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			_, err := Render([]byte(tt.input), "")
			if !errors.Is(err, ErrRenderInput) {
				t.Fatalf("Render() error = %v, want ErrRenderInput", err)
			}
		})
	}
}
