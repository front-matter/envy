package cmd

import (
	"errors"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

const renderTestManifest = `x-set-app: &app
  A: '${A}'
services:
  web:
    image: example
    environment:
      <<: [*app]
`

func writeRenderManifest(t *testing.T) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "compose.yml")
	if err := os.WriteFile(path, []byte(renderTestManifest), 0o644); err != nil {
		t.Fatalf("writing manifest: %v", err)
	}
	return path
}

func TestRenderComposeFileAddsSourceHeader(t *testing.T) {
	path := writeRenderManifest(t)

	got, err := renderComposeFile(path)
	if err != nil {
		t.Fatalf("renderComposeFile() error = %v", err)
	}
	if !strings.HasPrefix(string(got), "# Generated by envy render from compose.yml. Do not edit.\n") {
		t.Fatalf("missing header:\n%s", got)
	}
	if strings.Contains(string(got), "x-set-app") || !strings.Contains(string(got), "A: '${A}'") {
		t.Fatalf("unexpected rendering:\n%s", got)
	}
}

func TestCheckRendered(t *testing.T) {
	path := writeRenderManifest(t)
	rendered, err := renderComposeFile(path)
	if err != nil {
		t.Fatalf("renderComposeFile() error = %v", err)
	}
	dir := t.TempDir()

	tests := []struct {
		name    string
		content *string
		wantErr bool
	}{
		{name: "up to date", content: ptr(string(rendered)), wantErr: false},
		{name: "outdated", content: ptr("services: {}\n"), wantErr: true},
		{name: "missing", content: nil, wantErr: true},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			output := filepath.Join(dir, strings.ReplaceAll(tt.name, " ", "-")+".yml")
			if tt.content != nil {
				if err := os.WriteFile(output, []byte(*tt.content), 0o644); err != nil {
					t.Fatalf("writing output: %v", err)
				}
			}

			err := checkRendered(output, rendered)
			if tt.wantErr != (err != nil) {
				t.Fatalf("checkRendered() error = %v, wantErr %v", err, tt.wantErr)
			}
			if tt.wantErr && !errors.Is(err, ErrRenderOutdated) {
				t.Fatalf("checkRendered() error = %v, want ErrRenderOutdated", err)
			}
		})
	}
}

func ptr(s string) *string { return &s }
