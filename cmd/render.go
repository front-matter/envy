package cmd

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"path/filepath"

	"github.com/fatih/color"
	"github.com/front-matter/envy/compose"
	"github.com/spf13/cobra"
)

// ErrRenderOutdated is returned by "envy render --check" when the output file
// differs from a fresh rendering.
var ErrRenderOutdated = errors.New("rendered compose file is out of date")

var (
	renderOutput   string
	renderCheck    bool
	renderServices []string
)

var renderCmd = &cobra.Command{
	Use:   "render [path]",
	Short: "Render compose.yml without anchors, merge keys and x- fields",
	Long: `Render the compose manifest as a plain Compose file: anchors and merge keys
(including "<<: [*a, *b]") are expanded, top-level x- fields such as x-envy and
x-set-* are removed, and comments are dropped. Variables like ${VAR} are kept,
not interpolated. --service keeps only the given services, e.g. web and worker
for a platform that provides database, cache and search; depends_on entries
and volumes of the other services are removed with them.

Use it for platforms that do not handle YAML anchors well, and commit the
result next to the manifest. With --check, render compares the output file
with a fresh rendering and fails if it is out of date (for CI).

Examples:
  envy render
  envy render compose.yml --output compose.rendered.yml
  envy render compose.yml --output compose.rendered.yml --check
  envy render compose.yml --service web --service worker --output deploy/compose.yml`,
	Args: cobra.MaximumNArgs(1),
	RunE: func(cmd *cobra.Command, args []string) error {
		path, err := resolveValidateComposePath(args)
		if err != nil {
			return err
		}

		rendered, err := renderComposeFile(path)
		if err != nil {
			return err
		}

		if renderCheck {
			if renderOutput == "" {
				return fmt.Errorf("--check requires --output")
			}
			if err := checkRendered(renderOutput, rendered); err != nil {
				return err
			}
			color.Green("✅ %s is up to date\n", renderOutput)
			return nil
		}

		if renderOutput == "" {
			_, err := cmd.OutOrStdout().Write(rendered)
			return err
		}
		if err := os.WriteFile(renderOutput, rendered, 0o644); err != nil {
			return fmt.Errorf("writing %s: %w", renderOutput, err)
		}
		color.Green("✅ rendered %s to %s\n", path, renderOutput)
		return nil
	},
}

// renderComposeFile renders the manifest at path with a header naming its
// source file (base name only, so the output does not depend on the checkout
// location).
func renderComposeFile(path string) ([]byte, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("reading %s: %w", path, err)
	}
	header := fmt.Sprintf("Generated by envy render from %s. Do not edit.", filepath.Base(path))
	rendered, err := compose.Render(data, compose.RenderOptions{
		Header:   header,
		Services: renderServices,
	})
	if err != nil {
		return nil, fmt.Errorf("rendering %s: %w", path, err)
	}
	return rendered, nil
}

// checkRendered returns ErrRenderOutdated if the file at output differs from
// rendered or does not exist.
func checkRendered(output string, rendered []byte) error {
	existing, err := os.ReadFile(output)
	if err != nil {
		if os.IsNotExist(err) {
			return fmt.Errorf("%w: %s does not exist; run envy render --output %s", ErrRenderOutdated, output, output)
		}
		return fmt.Errorf("reading %s: %w", output, err)
	}
	if !bytes.Equal(existing, rendered) {
		return fmt.Errorf("%w: %s; run envy render --output %s", ErrRenderOutdated, output, output)
	}
	return nil
}

func init() {
	renderCmd.Flags().StringVarP(&renderOutput, "output", "o", "", "File to write the rendered compose file to (default: stdout)")
	renderCmd.Flags().BoolVar(&renderCheck, "check", false, "Fail if the --output file is not up to date (for CI)")
	renderCmd.Flags().StringSliceVar(&renderServices, "service", nil, "Keep only this service (repeatable, e.g. --service web --service worker)")
	rootCmd.AddCommand(renderCmd)
}
